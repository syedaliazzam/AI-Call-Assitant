/**
 * Every version of the company AI instructions an admin saved (ADR-0083), one row per save or
 * restore, never changed or deleted afterwards: a restore copies an older version's text into a new
 * row. A call pins the version ids in force when it started, so it can still read them after a later
 * save. Company text only: never call data, and it is never logged.
 */
export const aiInstructionsVersion = pgTable(
  'ai_instructions_version',
  {
    /** Random UUID (crypto.randomUUID()); a call sends it back as its pin. */
    id: text('id').primaryKey(),
    /** Which block: 'live' (live answers), 'notes' (AI notes) or 'ask' (Ask AI). */
    block: text('block').notNull(),
    /** The instructions, as the admin wrote them (line endings normalised); '' means none. */
    text: text('text').notNull(),
    /**
     * ADR-0086: the block's custom full system prompt, as JSON ({ part: text } for the block's parts,
     * cleaned and checked before saving), or null for the built-in prompt. Kept in the same version as
     * the instructions, so a call's pin covers both and its prompt cache never changes mid-call.
     */
    prompt: text('prompt'),
    /**
     * ADR-0087: for a custom prompt, the hash of the built-in prompt it was written against (a row of
     * ai_builtin_prompt), so the page can say when the built-in rules changed since. Null for the
     * built-in prompt, and for custom prompts saved before ADR-0087.
     */
    baseHash: text('base_hash'),
    /**
     * ADR-0089: the block's global system prompt as the admin wrote it (line endings normalised), sent
     * after the locked app contract. Null means the block's default prompt from the code. A row saved
     * before ADR-0089 also has null here: when its `text` or `prompt` is set, the server reads it as
     * the default prompt with its company instructions added (server/aiInstructions.ts). Rows saved
     * since ADR-0089 always leave `text` empty and `prompt` null.
     */
    globalPrompt: text('global_prompt'),
    /** ADR-0089: the admin's short note about this version ("Shorter sales answers"), or null. */
    note: text('note'),
    /** The admin who saved it; null once that account is deleted (the version stays). */
    authorId: text('author_id').references(() => user.id, { onDelete: 'set null' }),
    /** For a restore: the version whose text it copied; null for a normal save. */
    restoredFrom: text('restored_from'),
    /** When it was saved. */
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [
    // The database refuses an unknown block or an over-long text, whatever the code does.
    check('ai_instructions_version_block_check', sql`${table.block} in ('live', 'notes', 'ask')`),
    // The same 4,000-character limit as the page and the server (MAX_AI_INSTRUCTIONS_CHARS).
    check('ai_instructions_version_text_check', sql`char_length(${table.text}) <= 4000`),
    // ADR-0086: at most 3 parts of 40,000 characters (MAX_PROMPT_PART_CHARS) plus the JSON around them.
    check(
      'ai_instructions_version_prompt_check',
      sql`${table.prompt} is null or char_length(${table.prompt}) <= 130000`,
    ),
    // ADR-0089: the same 30,000-character limit as the page and the server (MAX_GLOBAL_PROMPT_CHARS).
    check(
      'ai_instructions_version_global_prompt_check',
      sql`${table.globalPrompt} is null or char_length(${table.globalPrompt}) <= 30000`,
    ),
    // ADR-0089: a short note (MAX_VERSION_NOTE_CHARS).
    check(
      'ai_instructions_version_note_check',
      sql`${table.note} is null or char_length(${table.note}) <= 200`,
    ),
    // The page lists one block's history, newest first.
    index('ai_instructions_version_block_created_idx').on(table.block, table.createdAt),
  ],
);

