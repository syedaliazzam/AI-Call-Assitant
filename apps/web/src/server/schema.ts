/**
 * The order of every change to synced call data (ADR-0049). Each insert, change or delete in
 * call_record takes the next number, so a record's `rev` says which copy is newer.
 */
export const callRecordRev = pgSequence('call_record_rev_seq');

/**
 * Each account's synced call data (ADR-0049): one row per record a device keeps (a session, a
 * document's text, a transcript line, an answer, notes, a lesson decision, a library item, a question
 * bank, an Ask AI chat, the default preferences, the account preferences). The record itself is
 * stored only as AES-256-GCM ciphertext in `content`; the other columns hold ids, flags and times,
 * never text from a call. A deleted record keeps its row as a tombstone (content removed), so the
 * account's other devices learn about the delete. Rows go when the account is deleted.
 */
export const callRecord = pgTable(
  'call_record',
  {
    /** The account the record belongs to. Every query is filtered by it (server/calldata). */
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    /** What the record is: 'session', 'document', 'utterance', … (SYNC_KINDS in @kite/shared). */
    kind: text('kind').notNull(),
    /** The record's id, made by the device (a UUID, or a transcript line's `session:call:line`). */
    id: text('id').notNull(),
    /** The session a document, line, answer, notes or question bank belongs to; else null. */
    sessionId: text('session_id'),
    /** This copy's revision, from call_record_rev_seq: higher is newer. */
    rev: bigint('rev', { mode: 'number' })
      .notNull()
      .default(sql`nextval('call_record_rev_seq')`),
    /** True for a tombstone: the record was deleted and its content removed. */
    deleted: boolean('deleted').default(false).notNull(),
    /** Which data key encrypted `content` (KITE_DATA_KEY_V<n>); null on a tombstone. */
    keyVersion: smallint('key_version'),
    /**
     * The record as JSON, encrypted with AES-256-GCM (base64 of IV + tag + ciphertext), bound to
     * this row's account, kind, id and key version. Null on a tombstone.
     */
    content: text('content'),
    /**
     * Sessions only: whether the session saves its transcript. Kept readable so the server can
     * refuse transcript lines for a session that does not save them (nothing about them is stored).
     */
    saveTranscript: boolean('save_transcript'),
    /** When this copy was written, to the millisecond; pulls read changes in this order. */
    updatedAt: timestamp('updated_at', { withTimezone: true, precision: 3 }).defaultNow().notNull(),
  },
  (table) => [
    // One copy per account, kind and id: another account's identical id is a different row.
    primaryKey({ columns: [table.userId, table.kind, table.id] }),
    // Pulls read one account's changes in time order, page by page.
    index('call_record_user_updated_idx').on(table.userId, table.updatedAt, table.kind, table.id),
    // Deleting a session finds its documents, lines, answers, notes and question bank.
    index('call_record_user_session_idx').on(table.userId, table.sessionId),
  ],
);

/**
 * Each account's Google Drive connection (ADR-0072): one row while connected. The refresh token is
 * stored only as AES-256-GCM ciphertext (the call_record pattern: KITE_DATA_KEY_V<n>, bound to this
 * account), never sent to a browser or logged. Disconnecting revokes the token at Google and deletes
 * the row; deleting the account deletes it too.
 */
export const googleDrive = pgTable('google_drive', {
  /** The account. One connection per account. */
  userId: text('user_id')
    .primaryKey()
    .references(() => user.id, { onDelete: 'cascade' }),
  /** Which data key encrypted the refresh token (KITE_DATA_KEY_V<n>). */
  keyVersion: smallint('key_version').notNull(),
  /** The Google refresh token, encrypted (base64 of IV + tag + ciphertext). */
  refreshToken: text('refresh_token').notNull(),
  /**
   * 'connected', or 'reconnect' once Google refused the token (revoked, expired after a testing
   * project's 7 days, or another OAuth client); uploads wait until the person connects again.
   */
  status: text('status').notNull().default('connected'),
  /** The Drive folder sessions are saved in (picked with Google Picker); null until picked. */
  folderId: text('folder_id'),
  /** That folder's name as Drive had it when picked, for Settings. Not call data. */
  folderName: text('folder_name'),
  /** The Shared Drive the folder is in; null for My Drive. */
  driveId: text('drive_id'),
  /** "Save calls to Google Drive" (on by default after connecting). */
  saveEnabled: boolean('save_enabled').default(true).notNull(),
  /** "Email me when a call is saved" (on by default; inert until SMTP is configured). */
  emailEnabled: boolean('email_enabled').default(true).notNull(),
  /** The team list for the "saved" email ("Also notify"), lower-case addresses. */
  alsoNotify: text('also_notify')
    .array()
    .default(sql`'{}'::text[]`)
    .notNull(),
  /** When the person last connected (a reconnect updates it). */
  connectedAt: timestamp('connected_at', { withTimezone: true }).defaultNow().notNull(),
  /** When the row last changed. */
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .defaultNow()
    .$onUpdate(() => /* @__PURE__ */ new Date())
    .notNull(),
});

/**
 * One row per call whose Drive uploads finished (ADR-0072; per call from ADR-0073, as a session can be
 * started again after it ended): the "saved" email's state, so each call gets at most one email (the
 * primary key) and Settings can list and retry them. What the
 * email says (title, date, length, file names, folder link, addresses) is stored only encrypted, like
 * call data; never transcript, notes, answer or document text, which the request cannot even carry.
 */
export const driveNotification = pgTable(
  'drive_notification',
  {
    /** The account. */
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    /**
     * The record's key (ADR-0073, server/google/report.ts notificationKey): the session's UUID for its
     * first record (its first call, or a whole session saved before ADR-0073), or
     * "<session UUID>~<call start, Unix ms>" for each later call. No migration: the column was already
     * text.
     */
    sessionId: text('session_id').notNull(),
    /** 'pending', 'sent', 'failed', 'off' (switched off) or 'not-set-up' (no SMTP settings). */
    status: text('status').notNull(),
    /** Which data key encrypted `content`. */
    keyVersion: smallint('key_version').notNull(),
    /** The email's details as JSON, encrypted with AES-256-GCM, bound to this account and record key. */
    content: text('content').notNull(),
    /** How many times sending was tried. */
    attempts: integer('attempts').default(0).notNull(),
    /** Why the last try failed, as a short code ('rejected', 'unreachable'); never a message. */
    error: text('error'),
    /** When the call's first report came. */
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    /** When the mail server accepted the email; null until then. */
    sentAt: timestamp('sent_at', { withTimezone: true }),
    /** When the row last changed. */
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
  },
  (table) => [
    // One email per call, ever: a second request finds the row and sends nothing.
    primaryKey({ columns: [table.userId, table.sessionId] }),
    // Settings lists one account's latest notifications.
    index('drive_notification_user_created_idx').on(table.userId, table.createdAt),
  ],
);
